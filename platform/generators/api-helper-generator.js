const fs = require('fs');
const path = require('path');
const { logger } = require('../../utils/base/logger');

/**
 * ============================================================================
 * API HELPER GENERATOR - Generate API Helper Methods
 * ============================================================================
 * 
 * Generates API helper method code in service helper files following the
 * existing pattern (e.g., PaymentHelper.processPayment())
 * 
 * Flow:
 * 1. Check if service helper file exists, create if not
 * 2. Generate method code from parsed cURL request
 * 3. Insert method into helper class
 * 4. Return method info for execution
 * 
 * USAGE:
 * ------
 * ```javascript
 * const generator = new ApiHelperGenerator();
 * const helperInfo = await generator.generateHelperMethod(
 *   parsedRequest,
 *   'payment-service',
 *   'process-payment'
 * );
 * ```
 * ============================================================================
 */

class ApiHelperGenerator {
  constructor() {
    this.servicesDir = path.resolve(__dirname, '../../services');
  }

  /**
   * Generate or update API helper method
   * @param {Object} parsedRequest - Parsed cURL request
   * @param {string} serviceName - Service name (e.g., 'payment-service')
   * @param {string} apiName - API name (e.g., 'process-payment')
   * @returns {Promise<Object>} Helper info { helperClass, methodName, filePath }
   */
  async generateHelperMethod(parsedRequest, serviceName, apiName) {
    // 1. Determine helper file path
    const helperFileName = `${serviceName}-helper.js`;
    const serviceDir = path.join(this.servicesDir, serviceName);
    const helperFilePath = path.join(serviceDir, helperFileName);

    // 2. Ensure service directory exists
    if (!fs.existsSync(serviceDir)) {
      fs.mkdirSync(serviceDir, { recursive: true });
      logger.info(`  Created service directory: ${serviceDir}`);
    }

    // 3. Check if helper file exists, create if not
    if (!fs.existsSync(helperFilePath)) {
      await this._createHelperFile(serviceName, helperFilePath);
    }

    // 4. Generate method code
    const methodCode = this._generateMethodCode(parsedRequest, apiName);
    const methodName = this._getMethodName(apiName);

    // 5. Insert method into helper file
    await this._insertMethodIntoHelper(helperFilePath, methodCode, methodName);

    // 6. Return helper info
    const helperClass = this._getHelperClassName(serviceName);
    
    return {
      helperClass,
      methodName,
      filePath: helperFilePath
    };
  }

  /**
   * Create new helper file from template
   * @private
   */
  async _createHelperFile(serviceName, helperFilePath) {
    const helperClass = this._getHelperClassName(serviceName);
    
    const template = `const { logger } = require('../../utils/base/logger');

/**
 * ${helperClass} - API Helper Methods
 * Auto-generated by API Helper Generator
 */
class ${helperClass} {
    // Methods will be added here automatically
}

module.exports = { ${helperClass} };
`;

    fs.writeFileSync(helperFilePath, template, 'utf8');
    logger.info(`  Created new helper file: ${helperFilePath}`);
  }

  /**
   * Generate method code from parsed request
   * @private
   */
  _generateMethodCode(parsedRequest, apiName) {
    const methodName = this._getMethodName(apiName);
    const { method, url, headers, body } = parsedRequest;

    // Generate parameters from body
    const params = this._inferParameters(body);
    
    // Generate JSDoc
    const jsdoc = this._generateJSDoc(apiName, params, method, url);

    // Clean headers (remove auth tokens for security)
    const safeHeaders = this._sanitizeHeaders(headers);

    // Generate method body
    const httpMethod = method.toLowerCase();
    const headersCode = safeHeaders && Object.keys(safeHeaders).length > 0
      ? `,\n            headers: ${JSON.stringify(safeHeaders, null, 16)}`
      : '';

    const methodBody = `
${jsdoc}
    static async ${methodName}(apiContext, payload) {
        logger.info(\`🔸 ${this._formatApiName(apiName)}: \${JSON.stringify(payload).substring(0, 100)}\`);

        const response = await apiContext.${httpMethod}('${url}', {
            data: payload${headersCode}
        });

        return response;
    }
`;

    return methodBody;
  }

  /**
   * Generate JSDoc for method
   * @private
   */
  _generateJSDoc(apiName, params, method, url) {
    const lines = [
      `    /**`,
      `     * ${this._formatApiName(apiName)}`,
      `     * Auto-generated from cURL`,
      `     * ${method} ${url}`,
      `     * `,
      `     * @param {Object} apiContext - Playwright API context`,
      `     * @param {Object} payload - Request payload`
    ];

    // Add parameter documentation
    if (params && params.length > 0) {
      params.forEach(param => {
        lines.push(`     * @param {${param.type}} payload.${param.name} - ${param.description}`);
      });
    }

    lines.push(`     * @returns {Promise<Object>} API response`);
    lines.push(`     */`);

    return lines.join('\n');
  }

  /**
   * Infer parameters from request body
   * @private
   */
  _inferParameters(body) {
    if (!body || typeof body !== 'object') {
      return [];
    }

    return Object.keys(body).map(key => {
      const value = body[key];
      const type = Array.isArray(value) ? 'Array' : typeof value;
      
      return {
        name: key,
        type: type.charAt(0).toUpperCase() + type.slice(1),
        description: `${key} value`
      };
    });
  }

  /**
   * Sanitize headers (remove sensitive data)
   * @private
   */
  _sanitizeHeaders(headers) {
    if (!headers) return null;

    const sanitized = { ...headers };
    
    // Remove authorization headers
    delete sanitized['Authorization'];
    delete sanitized['authorization'];
    
    // Remove tokens
    delete sanitized['X-Auth-Token'];
    delete sanitized['x-auth-token'];

    return Object.keys(sanitized).length > 0 ? sanitized : null;
  }

  /**
   * Insert method into existing helper class
   * @private
   */
  async _insertMethodIntoHelper(filePath, methodCode, methodName) {
    let content = fs.readFileSync(filePath, 'utf8');

    // Check if method already exists
    const methodExists = content.includes(`static async ${methodName}(`);

    if (methodExists) {
      logger.warn(`  ⚠️  Method ${methodName}() already exists. Skipping...`);
      return;
    }

    // Find module.exports position first
    const exportsPos = content.indexOf('module.exports');
    
    if (exportsPos === -1) {
      throw new Error(`Could not find module.exports in ${filePath}`);
    }

    // Find the closing brace of the class (before module.exports)
    const contentBeforeExports = content.substring(0, exportsPos);
    const classClosingBrace = contentBeforeExports.lastIndexOf('}');
    
    if (classClosingBrace === -1) {
      throw new Error(`Could not find class closing brace in ${filePath}`);
    }

    // Insert method before the class closing brace
    const beforeClosing = content.substring(0, classClosingBrace);
    const afterClosing = content.substring(classClosingBrace);

    const updatedContent = beforeClosing + methodCode + '\n' + afterClosing;

    fs.writeFileSync(filePath, updatedContent, 'utf8');
    logger.info(`  ✓ Added method ${methodName}() to helper class`);
  }

  /**
   * Convert API name to method name
   * 'process-payment' → 'processPayment'
   * @private
   */
  _getMethodName(apiName) {
    return apiName
      .split('-')
      .map((word, i) => i === 0 ? word : word.charAt(0).toUpperCase() + word.slice(1))
      .join('');
  }

  /**
   * Get helper class name from service name
   * 'payment-service' → 'PaymentHelper'
   * @private
   */
  _getHelperClassName(serviceName) {
    const baseName = serviceName.replace(/-service$/, '');
    const className = baseName
      .split('-')
      .map(word => word.charAt(0).toUpperCase() + word.slice(1))
      .join('');
    
    return `${className}Helper`;
  }

  /**
   * Format API name for display
   * 'process-payment' → 'Process Payment'
   * @private
   */
  _formatApiName(apiName) {
    return apiName
      .split('-')
      .map(word => word.charAt(0).toUpperCase() + word.slice(1))
      .join(' ');
  }
}

module.exports = { ApiHelperGenerator };