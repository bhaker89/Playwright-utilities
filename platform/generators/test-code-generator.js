const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');
const { LLMClient } = require('./llm-client');
const { ContextGatherer } = require('./context-gatherer');
const { PromptBuilder } = require('./prompt-builder');
const { logger } = require('../../utils/base/logger');

/**
 * ============================================================================
 * TEST CODE GENERATOR - Generate Test Code via LLM
 * ============================================================================
 * 
 * Main orchestrator for Step 4:
 * 1. Load OpenAPI spec
 * 2. Gather framework context
 * 3. Build LLM prompt
 * 4. Generate test code via LLM
 * 5. Validate and save test file
 * 
 * USAGE:
 * ------
 * ```javascript
 * const generator = new TestCodeGenerator();
 * const testPath = await generator.generate({
 *   serviceName: 'payment-service',
 *   apiName: 'process-payment',
 *   openApiSpecPath: 'services/.../openapi.yaml',
 *   helperInfo: { ... },
 *   llmProvider: 'openai'
 * });
 * ```
 * ============================================================================
 */

class TestCodeGenerator {
  constructor() {
    this.contextGatherer = new ContextGatherer();
    this.promptBuilder = new PromptBuilder();
    this.testsDir = path.resolve(__dirname, '../../tests/api');
  }

  /**
   * Generate test code using LLM
   * @param {Object} options
   * @param {string} options.serviceName - Service name
   * @param {string} options.apiName - API name
   * @param {string} options.openApiSpecPath - Path to OpenAPI spec
   * @param {Object} options.helperInfo - Helper class/method info
   * @param {string} [options.llmProvider='openai'] - LLM provider
   * @returns {Promise<string>} Path to generated test file
   */
  async generate(options) {
    const {
      serviceName,
      apiName,
      openApiSpecPath,
      helperInfo,
      llmProvider = 'openai'
    } = options;

    try {
      // 1. Load OpenAPI spec
      logger.info('  Loading OpenAPI specification...');
      const openApiSpec = fs.readFileSync(openApiSpecPath, 'utf8');
      logger.info('  ✓ OpenAPI spec loaded');

      // 2. Gather framework context
      const context = await this.contextGatherer.gatherContext(serviceName);

      // 3. Build LLM prompt
      const prompt = this.promptBuilder.buildTestGenerationPrompt({
        openApiSpec,
        context,
        helperInfo,
        serviceName,
        apiName
      });

      // 4. Generate test code via LLM
      logger.info('  Generating test code via LLM...');
      const llmClient = new LLMClient(llmProvider);

      const llmResponse = await llmClient.generate({
        prompt,
        maxTokens: 2500, // Slightly more for complex APIs
        temperature: 0.7
      });

      if (!llmResponse || !llmResponse.content) {
        throw new Error('LLM returned an empty response');
      }

      logger.info('  ✓ Test code generated by LLM');

      // 5. Extract and clean generated code
      const testCode = this._extractCode(llmResponse.content);

      // 6. Validate generated code
      logger.info('  Validating generated code...');
      this._validateCode(testCode);
      logger.info('  ✓ Code validation passed');

      // 7. Save test file
      const testFilePath = await this._saveTestFile(serviceName, apiName, testCode);

      logger.info('  ✓ Test file saved successfully');

      return testFilePath;

    } catch (error) {
      logger.error(`  ❌ Test generation failed: ${error.message}`);
      throw error;
    }
  }

  /**
   * Extract code from LLM response
   * @private
   */
  _extractCode(content) {
    // Remove markdown code fences if present
    let code = content.trim();

    // Remove ```javascript or ``` blocks
    code = code.replace(/^```(?:javascript|js)?\n/gm, '');
    code = code.replace(/\n```$/gm, '');
    code = code.trim();

    // If still wrapped, try to extract
    if (code.startsWith('```') && code.endsWith('```')) {
      const lines = code.split('\n');
      code = lines.slice(1, -1).join('\n');
    }

    return code;
  }

  /**
   * Validate generated code
   * @private
   */
  _validateCode(code) {
    // Check if code is not empty
    if (!code || code.length < 50) {
      throw new Error('Generated code is too short or empty');
    }

    // Check for required imports
    if (!code.includes('require')) {
      throw new Error('Generated code missing imports');
    }

    // Check for test structure
    if (!code.includes('test.describe') && !code.includes('test(')) {
      throw new Error('Generated code missing test structure');
    }

    // Check for assertions
    if (!code.includes('expect(')) {
      throw new Error('Generated code missing assertions');
    }

    // Basic syntax check (very simple)
    const openBraces = (code.match(/{/g) || []).length;
    const closeBraces = (code.match(/}/g) || []).length;

    if (Math.abs(openBraces - closeBraces) > 2) {
      logger.warn('  ⚠️  Possible brace mismatch detected');
    }

    logger.info('  ✓ Basic validation checks passed');
  }

  /**
   * Save test file
   * @private
   */
  async _saveTestFile(serviceName, apiName, testCode) {
    // Create service test directory
    const serviceTestDir = path.join(this.testsDir, serviceName);

    if (!fs.existsSync(serviceTestDir)) {
      fs.mkdirSync(serviceTestDir, { recursive: true });
      logger.info(`  Created test directory: ${serviceTestDir}`);
    }

    // Generate test file name
    const testFileName = `${apiName}.spec.js`;
    const testFilePath = path.join(serviceTestDir, testFileName);

    // Check if file already exists
    if (fs.existsSync(testFilePath)) {
      // Backup existing file
      const backupPath = `${testFilePath}.backup.${Date.now()}`;
      fs.copyFileSync(testFilePath, backupPath);
      logger.warn(`  ⚠️  Existing test backed up to: ${backupPath}`);
    }

    // Write test file
    fs.writeFileSync(testFilePath, testCode, 'utf8');

    return testFilePath;
  }
}

module.exports = { TestCodeGenerator };